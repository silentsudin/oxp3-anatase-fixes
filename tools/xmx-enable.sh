#!/bin/bash
# xmx-enable.sh enable|disable --game <dir with the game exe> --prefix <drive_c> [--force-fallback]
# Enables the XeSS XMX path (xess-xmx-linux) for one game on this driver stack:
#  * swaps the game's XeSS libraries for Intel SDK 3.0.2 ones (games older than XeSS 2.0.2.68 need that)
#  * writes ~/.config/xess-xmx/oxp3-env.sh with the driver + shim environment
#  * the shim is found through INTC_ALT_DRIVER_EXTENSIONS_PATH, so no Proton files are modified
# `disable` restores the game's own libraries and removes the env file.
set -eu
pkg=${XMX_PKG:-$HOME/.local/share/xess-xmx}
cache=${OXP3_CACHE:-$HOME/.cache/oxp3-fixes}
driver=$cache/mesa-xmx/usr/local/lib64/libvulkan_intel.so
envf=$HOME/.config/xess-xmx/oxp3-env.sh
action=${1:-}; shift || true
game= prefix= fallback=0
while [ $# -gt 0 ]; do case "$1" in
    --game) game=${2:-}; shift 2 ;;
    --prefix) prefix=${2:-}; shift 2 ;;
    --force-fallback) fallback=1; shift ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
esac; done
libs="libxess.dll libxess_dx11.dll libxess_fg.dll libxell.dll"
case "$action" in
enable)
    [ -n "$game" ] && [ -n "$prefix" ] || { echo "usage: $0 enable --game <bin dir> --prefix <drive_c>" >&2; exit 2; }
    [ -e "$driver" ] || { echo "error: build the driver first: tools/build-xmx-driver.sh" >&2; exit 1; }
    igc=${XMX_IGC_DIR:-${pkg_release:-$pkg}/igc}
    [ -x "$igc"/neo/bin/ocloc* ] 2>/dev/null || ls "$igc"/neo/bin/ocloc* >/dev/null 2>&1 \
        || { echo "error: no IGC ocloc under $igc; set XMX_IGC_DIR to the igc directory (the release archive ships none)" >&2; exit 1; }
    backup=$game/.xmx-orig; mkdir -p "$backup"
    for f in $libs; do
        [ -f "$game/$f" ] && [ ! -L "$game/$f" ] && { [ -e "$backup/$f" ] || cp -a "$game/$f" "$backup/"; cp -a "$pkg/xess/$f" "$game/$f"; }
    done
    mkdir -p "$(dirname "$envf")"
    cat > "$envf" <<ENV
# Generated by oxp3-anatase-fixes tools/xmx-enable.sh - source this before the game, or use the wrapper
export VK_DRIVER_FILES=$HOME/.config/xess-xmx/icd-xmx.json
export ANV_CM_KERNEL_DIR=$pkg/kernels
export ANV_CM_HELPER=$pkg/tools/cm-compile.sh
export VKD3D_DISABLE_EXTENSIONS=VK_EXT_descriptor_buffer
export force_vk_vendor=0
export INTC_ALT_DRIVER_EXTENSIONS_PATH=$pkg
$( [ "$fallback" = 1 ] && echo 'export IGDEXT_FORCE_FALLBACK=1' )
ENV
    mkdir -p "$HOME/.config/xess-xmx"
    printf '{"file_format_version":"1.0.0","ICD":{"library_path":"%s","api_version":"1.4.0"}}\n' "$driver" \
        > "$HOME/.config/xess-xmx/icd-xmx.json"
    echo "enabled: env in $envf (source it, or run the game through tools/xmx-run.sh)"
    echo "  game libs swapped (originals in $backup)"
    ;;
disable)
    [ -n "$game" ] || { echo "usage: $0 disable --game <bin dir>" >&2; exit 2; }
    backup=$game/.xmx-orig
    for f in $libs; do [ -e "$backup/$f" ] && cp -a "$backup/$f" "$game/$f"; done
    rm -f "$envf"
    echo "disabled: game libraries restored, $envf removed"
    ;;
*) echo "usage: $0 enable|disable --game <bin dir> --prefix <drive_c> [--force-fallback]" >&2; exit 2 ;;
esac
