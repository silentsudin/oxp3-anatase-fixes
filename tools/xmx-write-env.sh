#!/bin/bash
# SPDX-License-Identifier: MIT
# Write ~/.config/xess-xmx/oxp3-env.sh for the host Steam path.
#
# tools/xmx-enable.sh writes this file only when it swaps a specific game's XeSS
# libraries, so a machine that has not run that per-game step reports "session
# env not set". This writes the same environment from the detected driver, ICD
# and helper so tools/xmx-run.sh (or the Steam launch option) can source it.
set -euo pipefail
home=${HOME:?}
pkg=""
for d in "$home"/.local/share/xess-xmx-release/xess-xmx-linux-* "$home"/.local/share/xess-xmx; do
    [ -d "$d" ] && pkg=$d
done
repo=${OXP3_REPO:-$(cd "$(dirname "$0")/.." && pwd)}
helper=$repo/tools/xmx-cm-compile-nodgrf.sh
[ -x "$helper" ] || helper=$pkg/tools/cm-compile.sh
icd=$home/.config/xess-xmx/icd-xmx.json
kernels=$home/.cache/xess-xmx/kernels
[ -d "$kernels" ] || kernels=$pkg/kernels
# The ICD file is only needed while the installed Mesa has no CM injection (one Mesa:
# the driver itself is the XMX driver, so nothing else has to be selected).
icd_required=1
grep -aq ANV_CM_HELPER /usr/lib64/libvulkan_intel.so 2>/dev/null && icd_required=0
missing=0
(( icd_required )) && { [ -f "$icd" ] || { echo "missing ICD: $icd" >&2; missing=1; }; }
[ -x "$helper" ] || { echo "missing CM helper: $helper" >&2; missing=1; }
[ -d "$kernels" ] || { echo "missing kernel cache: $kernels" >&2; missing=1; }
if (( missing )); then
    echo "not writing oxp3-env.sh; fix the missing paths above (docs/xess-xmx.md)" >&2
    exit 1
fi
mkdir -p "$home/.config/xess-xmx"
icd_lines=""
if (( icd_required )); then
    icd_lines="export VK_DRIVER_FILES=$icd
export VK_ICD_FILENAMES=$icd"
fi
cat > "$home/.config/xess-xmx/oxp3-env.sh" <<ENV
# Generated by oxp3-anatase-fixes tools/xmx-write-env.sh - source this before the game, or use tools/xmx-run.sh
$icd_lines
export ANV_CM_KERNEL_DIR=$kernels
export ANV_CM_HELPER=$helper
export XMX_IGC_DIR=$pkg/igc
export INTC_ALT_DRIVER_EXTENSIONS_PATH=$pkg
export VKD3D_DISABLE_EXTENSIONS=VK_EXT_descriptor_buffer
export force_vk_vendor=0
ENV
echo "wrote $home/.config/xess-xmx/oxp3-env.sh"
