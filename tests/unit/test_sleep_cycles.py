"""Offline tests for the sleep-cycle harness analyser (tools/oxp3_sleep_cycles.py).

The harness exists to turn "the device stays warm and drains" into a number:
N real s2idle cycles, a guaranteed RTC wake, a named wake source, and drain per
hour with a verdict.  Everything here is the offline half:

* the pure maths (CLOCK_BOOTTIME minus CLOCK_MONOTONIC, %/h, awake cost),
* the attribution rules (RTC expected, power button, spurious xHCI, journal
  fallback),
* the validity rules (failed resume, implausible battery curve),
* the thresholds and their boundaries,
* the sysfs readers against a synthetic /sys tree.

No root, no suspend, no hardware, no network; only a private temporary
directory is written.  The fixture captures under tests/fixtures/sleep-cycles/
are synthetic and are generated by build-fixtures.py in that directory.
"""

from __future__ import annotations

import contextlib
import io
import json
import pathlib
import tempfile
import unittest
from unittest import mock

import support

mod = support.load("oxp3_sleep_cycles", "oxp3_sleep_cycles.py")

FIXTURES = support.REPO / "tests" / "fixtures" / "sleep-cycles"
TH = dict(mod.DEFAULT_THRESHOLDS)


def load_fixture(name):
    return json.loads((FIXTURES / (name + ".json")).read_text(encoding="utf-8"))


def analyse_fixture(name):
    return mod.analyse(load_fixture(name))


def capture_with(cycles=1, requested=60, energy_deltas=None, temp_rises=None,
                 wake_names=None, failed_resume=0, on_ac=False):
    """A minimal but complete capture for the threshold/boundary tests."""
    energy_deltas = list(energy_deltas or [0.012] * cycles)
    temp_rises = list(temp_rises or [1.0] * cycles)
    wake_names = list(wake_names or ["rtc_cmos"] * cycles)
    base = [
        {"id": "wakeup49", "name": "rtc_cmos", "event_count": 0,
         "device": "platform/rtc_cmos"},
        {"id": "wakeup39", "name": "PNP0C0C:00", "event_count": 0,
         "device": "platform/PNP0C0C:00"},
        {"id": "wakeup47", "name": "0000:00:14.0", "event_count": 0,
         "device": "pci0000:00/0000:00:14.0"},
    ]
    ids = {"rtc_cmos": "wakeup49", "PNP0C0C:00": "wakeup39",
           "0000:00:14.0": "wakeup47"}
    rows = []
    energy = 70.253
    success = 0
    total_hw = 0
    for index in range(1, cycles + 1):
        before_wake = [dict(item) for item in base]
        after_wake = [dict(item) for item in base]
        for entry in after_wake:
            if entry["id"] == ids.get(wake_names[(index - 1) % len(wake_names)]):
                entry["event_count"] = 1
        before_stats = {
            "success": success, "fail": 0, "failed_suspend": 0,
            "failed_resume": 0, "total_hw_sleep": total_hw,
        }
        success += 1
        total_hw += int(requested * 1e9)
        after_stats = {
            "success": success, "fail": 0, "failed_suspend": 0,
            "failed_resume": failed_resume if index == cycles else 0,
            "total_hw_sleep": total_hw,
        }
        rows.append(
            {
                "index": index,
                "requested_s": requested,
                "before": {
                    "energy_wh": energy, "energy_full_wh": 87.665,
                    "temp_max_c": 54.0, "suspend_stats": before_stats,
                    "wakeup_counts": before_wake,
                },
                "after": {
                    "energy_wh": round(energy - energy_deltas[index - 1], 6),
                    "energy_full_wh": 87.665,
                    "temp_max_c": 54.0 + temp_rises[index - 1],
                    "suspend_stats": after_stats,
                    "wakeup_counts": after_wake,
                },
                "boottime_ns": {
                    "before": index * 10**12,
                    "after": index * 10**12 + int((requested + 10) * 1e9),
                },
                "monotonic_ns": {
                    "before": index * 10**12,
                    "after": index * 10**12 + int(10 * 1e9),
                },
                "rtcwake": {"rc": 0, "seconds": requested, "log": ""},
                "settle": {"seconds": 10.0,
                           "energy_wh": round(energy - energy_deltas[index - 1]
                                               - 0.019, 6)},
                "journal": ["PM: suspend entry (s2idle)", "PM: suspend exit"],
            }
        )
        energy = round(energy - energy_deltas[index - 1], 6)
    return {
        "schema": 1, "tool": "sleep-cycle-test", "version": "1.0.0",
        "mode": "run", "notes": [],
        "meta": {
            "cycles_requested": cycles, "sleep_s": requested, "settle_s": 10,
            "on_ac": on_ac, "energy_full_wh": 87.665, "root": True,
            "rtc_cleanup": {"ok": True}, "thresholds": dict(TH),
        },
        "baseline": {"energy_wh": 70.253, "energy_full_wh": 87.665, "pct": 80,
                     "on_ac": on_ac, "rtc_alarm": {"rtc0": ""}},
        "cycles": rows,
    }


class FixtureVerdictTest(unittest.TestCase):
    """One fixture per failure mode the harness must recognise."""

    def test_good_rtc_cycles(self):
        report = analyse_fixture("three-good-rtc")
        self.assertEqual(report["verdict"]["label"], "GOOD")
        self.assertEqual(report["verdict"]["code"], 0)
        self.assertEqual(len(report["cycles"]), 3)
        self.assertAlmostEqual(report["summary"]["drain_pct_per_h"], 0.82, places=1)
        self.assertAlmostEqual(report["summary"]["temp_rise_max_c"], 1.2, places=1)
        self.assertEqual(report["wake"]["kind"], "rtc")
        self.assertTrue(report["wake"]["expected"])
        self.assertGreater(report["summary"]["uncertainty_pct_per_h"], 0.0)
        self.assertAlmostEqual(report["summary"]["awake_cost_wh"], 0.059, places=2)

    def test_power_button_wake_is_named_and_capped_at_investigate(self):
        report = analyse_fixture("power-button-wake")
        self.assertEqual(report["verdict"]["label"], "INVESTIGATE")
        self.assertEqual(report["verdict"]["code"], 1)
        self.assertEqual(report["wake"]["kind"], "power-button")
        self.assertEqual(report["wake"]["dominant"]["name"], "PNP0C0C:00")
        self.assertFalse(report["wake"]["expected"])
        self.assertTrue(
            any("woke on" in reason for reason in report["verdict"]["reasons"])
        )

    def test_spurious_xhci_wake_is_named(self):
        report = analyse_fixture("spurious-xhci")
        self.assertEqual(report["verdict"]["label"], "INVESTIGATE")
        self.assertEqual(report["wake"]["kind"], "pci")
        self.assertEqual(report["wake"]["dominant"]["name"], "0000:00:14.0")
        self.assertIn("USB xHCI", report["wake"]["text"])
        self.assertFalse(report["wake"]["expected"])

    def test_failed_resume_is_failing(self):
        report = analyse_fixture("failed-resume")
        self.assertEqual(report["verdict"]["label"], "FAILING")
        row = report["cycles"][0]
        self.assertEqual(row["status"], "failed")
        self.assertEqual(row["suspend_stats"]["failed_resume"], 1)
        self.assertTrue(
            any(issue["code"] == "failed-resume" for issue in row["issues"])
        )
        self.assertFalse(row["journal"]["suspend_exit"])

    def test_battery_increase_is_invalid_not_a_negative_drain(self):
        report = analyse_fixture("battery-increase")
        self.assertEqual(report["verdict"]["label"], "INVALID")
        self.assertEqual(report["verdict"]["code"], 2)
        row = report["cycles"][0]
        self.assertEqual(row["status"], "invalid")
        self.assertTrue(
            any(issue["code"] == "energy-increased" for issue in row["issues"])
        )
        # The completed suspend time is still reported honestly, even though no
        # rate can be computed from this cycle.
        self.assertEqual(report["summary"]["suspended_s"], 60.0)
        self.assertEqual(report["summary"]["valid_cycles"], 0)

    def test_high_drain_is_failing(self):
        report = analyse_fixture("high-drain")
        self.assertEqual(report["verdict"]["label"], "FAILING")
        self.assertGreater(report["summary"]["drain_pct_per_h"], 3.0)
        self.assertGreaterEqual(report["summary"]["temp_rise_max_c"], 3.0)

    def test_journal_fallback_names_the_source(self):
        report = analyse_fixture("journal-fallback")
        self.assertEqual(report["verdict"]["label"], "GOOD")
        self.assertEqual(report["cycles"][0]["wake"]["from"], "journal")
        self.assertEqual(report["wake"]["kind"], "rtc")
        self.assertEqual(report["wake"]["dominant"]["name"], "rtc_cmos")


class MathsTest(unittest.TestCase):
    def test_slept_seconds_uses_boottime_minus_monotonic(self):
        cycle = {
            "boottime_ns": {"before": 0, "after": 70_000_000_000},
            "monotonic_ns": {"before": 0, "after": 10_000_000_000},
        }
        self.assertAlmostEqual(mod.slept_seconds(cycle), 60.0, places=6)
        self.assertAlmostEqual(mod.awake_seconds(cycle), 10.0, places=6)
        self.assertAlmostEqual(mod.total_seconds(cycle), 70.0, places=6)

    def test_missing_clocks_return_none(self):
        self.assertIsNone(mod.slept_seconds({}))
        self.assertIsNone(mod.total_seconds({"boottime_ns": {"before": 1}}))

    def test_drain_pct_per_h_normalises_to_full_pack(self):
        # 1 %/h of an 87.7 Wh pack is 0.877 Wh/h.
        self.assertAlmostEqual(mod.drain_pct_per_h(0.877, 87.7, 1.0), 1.0, places=6)
        self.assertAlmostEqual(mod.drain_pct_per_h(0.877, 87.7, 0.5), 2.0, places=6)
        self.assertIsNone(mod.drain_pct_per_h(0.1, 0, 1.0))
        self.assertIsNone(mod.drain_pct_per_h(0.1, 87.7, 0))

    def test_settle_awake_watts(self):
        cycle = {
            "after": {"energy_wh": 70.0},
            "settle": {"seconds": 10.0, "energy_wh": 69.981},
        }
        self.assertAlmostEqual(mod.settle_awake_w(cycle), 6.84, places=2)
        self.assertIsNone(mod.settle_awake_w({"after": {"energy_wh": 70.0}}))

    def test_energy_and_temperature_deltas(self):
        cycle = {
            "before": {"energy_wh": 70.0, "temp_max_c": 54.0},
            "after": {"energy_wh": 69.988, "temp_max_c": 55.2},
        }
        self.assertAlmostEqual(mod.energy_delta_wh(cycle), 0.012, places=6)
        self.assertAlmostEqual(mod.temp_rise_c(cycle), 1.2, places=6)

    def test_wake_deltas_ignore_zero_and_negative_moves(self):
        cycle = {
            "before": {"wakeup_counts": [
                {"id": "a", "name": "rtc_cmos", "event_count": 3},
                {"id": "b", "name": "PNP0C0C:00", "event_count": 5},
                {"id": "c", "name": "0000:00:14.0", "event_count": 50},
            ]},
            "after": {"wakeup_counts": [
                {"id": "a", "name": "rtc_cmos", "event_count": 4},
                {"id": "b", "name": "PNP0C0C:00", "event_count": 5},
                {"id": "c", "name": "0000:00:14.0", "event_count": 49},
            ]},
        }
        deltas = mod.wake_deltas(cycle)
        self.assertEqual(len(deltas), 1)
        self.assertEqual(deltas[0]["name"], "rtc_cmos")
        self.assertEqual(deltas[0]["delta"], 1)

    def test_rtc_plus_usb_is_not_an_expected_wake(self):
        cycle = {
            "before": {"wakeup_counts": [
                {"id": "a", "name": "rtc_cmos", "event_count": 0},
                {"id": "b", "name": "0000:00:14.0", "event_count": 0},
            ]},
            "after": {"wakeup_counts": [
                {"id": "a", "name": "rtc_cmos", "event_count": 1},
                {"id": "b", "name": "0000:00:14.0", "event_count": 1},
            ]},
        }
        wake = mod.classify_cycle_wake(cycle)
        self.assertFalse(wake["expected"])
        self.assertEqual(
            [source["name"] for source in wake["sources"]],
            ["0000:00:14.0", "rtc_cmos"],
        )

    def test_classify_known_sources(self):
        self.assertEqual(mod.wake_kind({"name": "rtc_cmos", "device": ""}), "rtc")
        self.assertEqual(mod.wake_kind({"name": "alarmtimer.0.auto", "device": ""}),
                         "rtc")
        self.assertEqual(mod.wake_kind({"name": "PNP0C0C:00", "device": ""}),
                         "power-button")
        self.assertEqual(mod.wake_kind({"name": "PNP0C0D:00", "device": ""}), "lid")
        self.assertEqual(mod.wake_kind({"name": "3-4", "device": "usb3/3-4"}), "usb")
        self.assertEqual(mod.wake_kind({"name": "ACPI000E:00", "device": ""}), "rtc")
        self.assertEqual(mod.wake_kind({"name": "mystery", "device": ""}), "other")


class ThresholdTest(unittest.TestCase):
    def test_just_under_one_percent_is_good(self):
        # 60 s window of an 87.665 Wh pack: 0.014 Wh is 0.958 %/h.
        report = mod.analyse(capture_with(energy_deltas=[0.014]))
        self.assertEqual(report["verdict"]["label"], "GOOD")

    def test_exactly_one_percent_is_investigate(self):
        delta = 87.665 * (60.0 / 3600.0) / 100.0  # exactly 1.0 %/h
        report = mod.analyse(capture_with(energy_deltas=[delta]))
        self.assertEqual(report["verdict"]["label"], "INVESTIGATE")

    def test_exactly_three_percent_is_investigate_and_above_is_failing(self):
        delta = 87.665 * (60.0 / 3600.0) / 100.0 * 3.0
        self.assertEqual(
            mod.analyse(capture_with(energy_deltas=[delta]))["verdict"]["label"],
            "INVESTIGATE",
        )
        report = mod.analyse(capture_with(energy_deltas=[delta * 1.1]))
        self.assertEqual(report["verdict"]["label"], "FAILING")

    def test_two_degree_rise_is_investigate(self):
        report = mod.analyse(capture_with(temp_rises=[2.0]))
        self.assertEqual(report["verdict"]["label"], "INVESTIGATE")
        report = mod.analyse(capture_with(temp_rises=[1.9]))
        self.assertEqual(report["verdict"]["label"], "GOOD")

    def test_on_ac_is_invalid_even_with_good_numbers(self):
        report = mod.analyse(capture_with(on_ac=True))
        self.assertEqual(report["verdict"]["label"], "INVALID")
        self.assertEqual(report["verdict"]["code"], 2)

    def test_partial_run_is_at_least_investigate(self):
        capture = capture_with(cycles=3)
        capture["meta"]["cycles_requested"] = 3
        capture["cycles"] = capture["cycles"][:2]
        capture["meta"]["interrupted"] = True
        report = mod.analyse(capture)
        self.assertNotEqual(report["verdict"]["label"], "GOOD")
        self.assertTrue(
            any("only 2 of the 3" in reason for reason in report["verdict"]["reasons"])
        )

    def test_refused_suspend_is_failing(self):
        capture = capture_with(cycles=1)
        capture["cycles"][0]["rtcwake"] = {"rc": 1, "seconds": 60, "log": "denied"}
        report = mod.analyse(capture)
        self.assertEqual(report["verdict"]["label"], "FAILING")
        self.assertEqual(report["cycles"][0]["status"], "failed")

    def test_rtcwake_timeout_is_failing(self):
        capture = capture_with(cycles=1)
        capture["cycles"][0]["rtcwake"] = {
            "rc": None, "seconds": 60, "log": "", "timed_out": True,
        }
        report = mod.analyse(capture)
        self.assertEqual(report["verdict"]["label"], "FAILING")
        self.assertTrue(
            any(issue["code"] == "rtcwake-timeout"
                for issue in report["cycles"][0]["issues"])
        )

    def test_one_invalid_cycle_caps_the_run_at_investigate(self):
        capture = capture_with(cycles=2, energy_deltas=[0.012, -0.10])
        report = mod.analyse(capture)
        self.assertEqual(report["verdict"]["label"], "INVESTIGATE")
        self.assertEqual(report["summary"]["valid_cycles"], 1)
        self.assertEqual(report["summary"]["invalid_cycles"], 1)

    def test_no_cycles_is_invalid(self):
        capture = capture_with(cycles=1)
        capture["cycles"] = []
        report = mod.analyse(capture)
        self.assertEqual(report["verdict"]["label"], "INVALID")


